def event_prompt(state: GameState) -> str:
    """事件专用的补充提示; 目前只覆盖涅奥开局事件."""
    event = state.raw.get("event") or {}
    event_id = str(event.get("event_id") or event.get("event_name") or "")
    if event_id.upper() == "NEOW" or event_id == "涅奥":
        return NEOW_GUIDE
    return ""


